package am.furnituredetailing.design;

/**
 * Builds the instruction that turns a furniture photo into constructor modules.
 */
public final class FurniturePrompt {

    private FurniturePrompt() {
    }

    public static String build(DesignRequest r, int imageCount) {
        return build(r, imageCount, 0);
    }

    /** Images are attached in order: first {@code imageCount} of the piece, then {@code roomCount} of the room. */
    public static String build(DesignRequest r, int imageCount, int roomCount) {
        String dims = "ширина %s, высота %s, глубина %s".formatted(orNa(r.width()), orNa(r.height()), orNa(r.depth()));
        String notes = r.notes() == null || r.notes().isBlank() ? "нет" : r.notes().strip();
        String photo = imageCount > 0
                ? "Приложено фото/эскиз (%d шт.). Опирайся на него.".formatted(imageCount)
                : "Фото мебели нет, работай по описанию.";
        String room = roomCount > 0 ? """

                Далее приложено фото помещения (%d шт.): место, куда встанет мебель. Это НЕ образец дизайна.
                Внимательно найди на нём всё, что мешает или влияет на размеры и конструкцию:
                коллекторы (водяные, отопительные), счётчики, трубы и стояки, радиаторы, электрощиток, розетки и выключатели,
                вентиляционные решётки и короба, газовые трубы и краны, окна и подоконники, подъёмы и дверные проёмы
                (куда открываются двери), плинтусы и наличники, скошенный потолок и неровные стены, батареи под окном.
                Если из-за этого нужно уменьшить габарит, добавить вырез или оставить доступ (например, к коллектору или щитку),
                учти это в размерах модулей и напиши в siteNotes. Не выдумывай то, чего не видно на фото.
                """.formatted(roomCount) : "";
        return """
                Ты технолог корпусной мебели из ЛДСП %d мм. %s

                Общие габариты от заказчика (мм): %s.
                Пожелания: %s.

                Программа раскроя умеет только такие модули (каждый — отдельный корпус-короб):
                - корпус: 2 боковины, дно, крышка (top:"solid") или 2 царги под столешницу (top:"rails");
                - внутри: partitions вертикальных перегородок делят корпус на равные секции; shelves полок в КАЖДОЙ секции;
                - фасады накладные: drawers ящиков одной высоты dh стопкой ВНИЗУ на всю ширину, над ними doors одинаковых дверей на оставшуюся высоту; ширина двери не больше 600 мм;
                - base: "none" | "legs" (legH) | "plinth" (plinthH, цоколь из ЛДСП);
                - rod: штанга для одежды; hang: навесной модуль; back: задняя стенка ДВП.

                Если мебель сложнее (секция с ящиками рядом с распашной, антресоль, открытая ниша, сиденье),
                РАЗБЕЙ её на несколько модулей, стоящих рядом или друг на друге, так чтобы в каждой вертикальной
                колонке сумма высот, а в каждом ряду сумма ширин совпадала с общими габаритами.
                Если габарит не указан — оцени по пропорциям и стандартам (глубина шкафа 550–600, комода 450,
                кухня низ 560×820, верх 300×720). Высота ящика dh обычно 150–250 мм, шаг полок 300–400 мм.
                Названия модулей начинай с зоны: «Л:», «Ц:», «П:» (лево, центр, право), если зон несколько.
                Для каждого модуля укажи положение в сборке: x — мм от левого края изделия до левой стороны модуля,
                y — мм от пола до низа модуля (антресоль над шкафом высотой 2100 имеет y=2100).
                Модули не должны пересекаться, а вместе должны заполнять общий габарит.

                Ответь ТОЛЬКО одним JSON-объектом без пояснений:
                {"summary":"2-4 предложения по-русски: что видно и как разбил",
                 "modules":[{"type":"wardrobe|dresser|kitchenLow|kitchenUp|rack|tumba","name":"короткое название",
                   "W":0,"H":0,"D":0,"doors":0,"drawers":0,"dh":0,"partitions":0,"shelves":0,"removable":true,
                   "top":"solid|rails","base":"none|legs|plinth","legH":100,"plinthH":80,"rod":false,"back":true,"hang":false,
                   "x":0,"y":0}],
                 "notes":["допущения и что не входит в расчёт: зеркала, крючки, мягкие элементы, фрезеровка"],
                 "siteNotes":["что учесть на месте по фото помещения: препятствия, замеры, которые нужно уточнить; [] если фото помещения нет"]}
                """.formatted(r.thickness(), photo + room, dims, notes);
    }

    private static String orNa(Integer v) {
        return v == null || v <= 0 ? "не указана" : v.toString();
    }
}
